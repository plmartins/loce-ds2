import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// border-beam doesn't export its color stops. Read the installed, pinned
// preset at build time so the DS never maintains a second rainbow by hand.
const source = readFileSync(fileURLToPath(import.meta.resolve('border-beam')), 'utf8');
const border = source.match(/colorful:\s*\{\s*border:\s*\[([\s\S]*?)\]/)?.[1];
const colors = [...(border ?? '').matchAll(/color:\s*"(rgb\(\d+,\s*\d+,\s*\d+\))"/g)].map(match => match[1]);
if (colors.length !== 9) throw new Error('The border-beam colorful preset changed. Review the AI palette adapter before building.');
const stops = { orange: 6, red: 0, pink: 7, violet: 8, indigo: 4, blue: 1, teal: 3, green: 2 };
const tokens = Object.entries(stops).map(([name, index]) => `    --ai-spectrum-${name}: ${colors[index]};`).join('\n');
const output = `/* Generated by scripts/sync-ai-palette.mjs from border-beam's colorful preset. */\n:root {\n${tokens}\n}\n`;
const target = new URL('../src/styles/ai-palette.css', import.meta.url);
let previous;
try { previous = readFileSync(target, 'utf8'); } catch { /* first build */ }
if (previous !== output) writeFileSync(target, output);
